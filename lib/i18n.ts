export const dictionaries: Record<Locale, Dict> = { id, en };

/** Terjemahkan `key` pada `locale`, dengan fallback ke id lalu ke key. */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  let s = dictionaries[locale][key] ?? dictionaries.id[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      s = s.replaceAll(`{${name}}`, String(value));
    }
  }
  return s;
}
